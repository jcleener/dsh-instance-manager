import test from 'node:test';
import assert from 'node:assert/strict';
import { restartTool } from '../code/tools.js';
import { startRestoreMonitor } from '../code/restore.js';
test('tool binds original session, only submits after authorization', async () => {
  let restarts = 0, prepared = 0, lastPlan;
  const manager = { status: async () => ({ ok: true }), preflight: async () => ({ ok: true }),
    prepareRestart: async plan => { prepared++; lastPlan = plan; return { ok: true, plan }; },
    requestPreparedRestart: async id => { restarts++; assert.equal(id, lastPlan.requestId); return { ok: true }; } };
  let allowed = false, concluded = false;
  const tool = restartTool({ manager, controller: { inspect: async () => ({ meta: { id: 'original-session' } }) }, approval: { request: async () => allowed ? 'allowed-once' : 'rejected' } });
  const exec = { agent: { id: 'original-session' }, signal: new AbortController().signal, concludeTurn: () => { concluded = true; } };
  await tool.execute({ action: 'preflight', pluginName: 'sample' }, exec);
  await tool.execute({ action: 'restart', pluginName: 'sample' }, exec);
  assert.equal(restarts, 0);
  allowed = true;
  const accepted = await tool.execute({ action: 'restart', pluginName: 'sample', report: { reason: 'reload plugin', verifyAfterRestart: ['check active'], handoff: '继续检查插件状态。' }, resumeSession: true }, exec);
  assert.equal(accepted.phase, 'waiting-for-idle'); assert.equal(prepared, 1); assert.equal(restarts, 0); assert.equal(lastPlan.sessionId, exec.agent.id); assert.equal(concluded, true);
  await new Promise(resolve => setTimeout(resolve, 1250));
  assert.equal(restarts, 1);
  await assert.rejects(tool.execute({ action: 'restart', command: 'bad' }, exec), /字段/);
});
test('child agent cannot submit restart or bind its own continuation', async () => {
  let restarts = 0;
  const tool = restartTool({ manager: { preflight: async () => ({ ok: true }), restart: async () => { restarts++; } },
    approval: { request: async () => 'allowed-once' }, controller: { inspect: async () => ({ meta: { parentSession: 'parent', origin: 'subagent' } }) } });
  await assert.rejects(tool.execute({ action: 'restart', pluginName: 'sample', resumeSession: true },
    { agent: { id: 'child' }, signal: new AbortController().signal }), /原主会话/);
  assert.equal(restarts, 0);
});
test('restore only runs after ready, claims before single delivery', async () => {
  let calls = [], finish;
  const done = new Promise(r => { finish = r; });
  const notice = { phase: 'ready', details: { requestId: 'req', sessionId: 'original' } };
  const stop = startRestoreMonitor({ status: async () => ({ daemon: notice }), claim: async () => { calls.push('claim'); return { status: notice }; },
    controller: { prompt: async (req, signal) => { calls.push('prompt'); assert.equal(req.sessionId, 'original'); assert.ok(signal); } },
    log: event => { calls.push(event); finish(); }, intervalMs: 5 });
  await done; stop();
  assert.deepEqual(calls, ['claim', 'prompt', 'restore-notification-sent']);
});
test('failed prompt is not retried or regenerated by LLM', async () => {
  let claims = 0, prompts = 0, finish;
  const done = new Promise(r => { finish = r; });
  const notice = { phase: 'recovered', details: { requestId: 'req', sessionId: 's', disabledPlugin: 'sample' } };
  const stop = startRestoreMonitor({ status: async () => ({ daemon: notice }), claim: async () => { claims++; return { status: notice }; },
    controller: { prompt: async () => { prompts++; throw new Error('admission failed'); } }, log: () => finish(), intervalMs: 5 });
  await done; stop(); assert.equal(claims, 1); assert.equal(prompts, 1);
});
